import 'dart:convert';
import 'dart:io';

Never _fail(String message) {
  stderr.writeln('Selah Xcode configuration failed: $message');
  exit(1);
}

Map<String, dynamic> _readJson(File file) {
  if (!file.existsSync()) _fail('missing ${file.path}');
  final decoded = jsonDecode(file.readAsStringSync());
  if (decoded is! Map<String, dynamic>) {
    _fail('invalid JSON object in ${file.path}');
  }
  return decoded;
}

String _requiredString(Map<String, dynamic> values, String key) {
  final value = values[key];
  if (value is! String || value.isEmpty) {
    _fail('missing $key in pinned Flutter version manifest');
  }
  return value;
}

String _encodeDefine(String value) => base64Encode(utf8.encode(value));

void main(List<String> arguments) {
  if (arguments.length != 2) {
    _fail('usage: generate_xcode_config.dart PROJECT_ROOT FLUTTER_ROOT');
  }

  final project = Directory(arguments[0]).resolveSymbolicLinksSync();
  final flutterRoot = Directory(arguments[1]).resolveSymbolicLinksSync();
  final manifest = _readJson(File('$flutterRoot/bin/cache/flutter.version.json'));

  if (_requiredString(manifest, 'flutterVersion') != '3.44.2' ||
      _requiredString(manifest, 'channel') != 'stable' ||
      _requiredString(manifest, 'dartSdkVersion') != '3.12.2') {
    _fail('the pinned Flutter/Dart identity changed');
  }

  final pubspec = File('$project/pubspec.yaml');
  if (!pubspec.existsSync()) _fail('missing ${pubspec.path}');
  final versionMatch = RegExp(
    r'^version:\s*([^\s+]+)(?:\+([^\s]+))?\s*$',
    multiLine: true,
  ).firstMatch(pubspec.readAsStringSync());
  if (versionMatch == null) _fail('pubspec.yaml has no valid version');
  final buildName = versionMatch.group(1)!;
  final buildNumber = versionMatch.group(2) ?? '1';

  final packageConfig = File('$project/.dart_tool/package_config.json');
  if (!packageConfig.existsSync()) _fail('missing ${packageConfig.path}');
  final frameworkPackage = Directory(
    '$project/ios/Flutter/ephemeral/Packages/.packages/FlutterFramework',
  );
  if (!frameworkPackage.existsSync()) {
    _fail('prepared local FlutterFramework Swift package is missing');
  }

  final frameworkRevision = _requiredString(manifest, 'frameworkRevision');
  final engineRevision = _requiredString(manifest, 'engineRevision');
  final defines = <String>[
    'SELAH_DRAFT_LOCAL_ONLY=true',
    'FLUTTER_APP_FLAVOR=draft',
    'FLUTTER_VERSION=${_requiredString(manifest, 'flutterVersion')}',
    'FLUTTER_CHANNEL=${_requiredString(manifest, 'channel')}',
    'FLUTTER_GIT_URL=${_requiredString(manifest, 'repositoryUrl')}',
    'FLUTTER_FRAMEWORK_REVISION=${frameworkRevision.substring(0, 10)}',
    'FLUTTER_ENGINE_REVISION=${engineRevision.substring(0, 10)}',
    'FLUTTER_DART_VERSION=${_requiredString(manifest, 'dartSdkVersion')}',
  ].map(_encodeDefine).join(',');

  final content = <String>[
    '// Generated by Selah\'s local-only delivery route; do not edit.',
    'FLUTTER_ROOT=$flutterRoot',
    'FLUTTER_APPLICATION_PATH=$project',
    'FLUTTER_FRAMEWORK_SWIFT_PACKAGE_PATH=${frameworkPackage.path}',
    'COCOAPODS_PARALLEL_CODE_SIGN=true',
    'FLUTTER_TARGET=$project/lib/main.dart',
    'FLUTTER_BUILD_DIR=build',
    'FLUTTER_BUILD_NAME=$buildName',
    'FLUTTER_BUILD_NUMBER=$buildNumber',
    'EXCLUDED_ARCHS[sdk=iphonesimulator*]=i386',
    'EXCLUDED_ARCHS[sdk=iphoneos*]=armv7',
    'DART_DEFINES=$defines',
    'DART_OBFUSCATION=false',
    'TRACK_WIDGET_CREATION=true',
    'TREE_SHAKE_ICONS=false',
    'PACKAGE_CONFIG=${packageConfig.path}',
    'FLAVOR=draft',
    '',
  ].join('\n');

  final output = File('$project/ios/Flutter/Generated.xcconfig');
  if (!output.existsSync() || output.readAsStringSync() != content) {
    output.writeAsStringSync(content, flush: true);
  }
  stdout.writeln('Generated locked Selah Profile-draft Xcode settings.');
}
