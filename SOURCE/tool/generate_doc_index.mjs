import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const docs = [];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isSymbolicLink()) continue;
    if (e.isDirectory()) walk(p);
    else if (e.name.endsWith('.md')) docs.push(path.relative(project, p));
  }
}
walk(path.join(project, 'APP'));
walk(path.join(project, 'SYSTEM/DOCUMENTS'));
walk(path.join(project, 'SYSTEM/OUTSTANDING_ACTIONS'));
const output = '# Selah documentation index\n\nGenerated by SOURCE/tool/generate_doc_index.mjs.\n\n' +
  [...new Set(docs)].sort().map(p => `- ${p}`).join('\n') + '\n';
fs.writeFileSync(path.join(project, 'SYSTEM/DOCUMENTATION_INDEX.md'), output);
console.log(`Generated index of ${docs.length} Selah project documents.`);
